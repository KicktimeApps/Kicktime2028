const BY_CODE = new Map(NATIONS.map((n) => [n.code, n]));

export function getNation(code: string | null | undefined): Nation | undefined {
  return code ? BY_CODE.get(code) : undefined;
}

export function isNationCode(code: string | null | undefined): boolean {
  return !!code && BY_CODE.has(code);
}

