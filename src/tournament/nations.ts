const normalize = (s: string) => s.trim().toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "");

const LOOKUP: Map<string, string> = (() => {
  const idx = new Map<string, string>();
  for (const n of NATIONS) {
    for (const key of [n.code, n.name, n.short, ...n.aliases]) {
      idx.set(key.toLowerCase(), n.code);
      idx.set(normalize(key), n.code);
    }
  }
  return idx;
})();

/**
 * Ordnet einen Teamnamen aus einer Live-Datenquelle (deutsch, englisch oder
 * Kürzel) einem FIFA-Kürzel zu. Unbekannte Namen → null (z. B. Testdaten wie
 * „SV Großefehn“, die in OpenLigaDB vorkommen).
 */
export function nationFromName(name: string | null | undefined): string | null {
  if (!name) return null;
  return LOOKUP.get(name.trim().toLowerCase()) ?? LOOKUP.get(normalize(name)) ?? null;
}
